        request_url = request_data['url']
        
        # Verify URL is properly formatted (should be valid URL without unescaped spaces)
        assert ' ' not in request_url or '%20' in request_url, \
            f"URL should not contain unescaped spaces: {request_url}"
        
        # Verify the URL can be parsed correctly
        try:
            parsed_url = urlparse(request_url)
            query_params = parse_qs(parsed_url.query)
            # If we got here, the URL is properly encoded
            assert True, "URL is properly encoded"
        except Exception as e:
            pytest.fail(f"URL parsing failed, URL may not be properly encoded: {request_url}, Error: {str(e)}")

